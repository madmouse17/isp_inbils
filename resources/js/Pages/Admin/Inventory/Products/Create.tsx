import type { FormEvent } from 'react';
import { Link, router, useForm } from '@inertiajs/react';
import { ArrowLeft } from 'lucide-react';
import AdminLayout from '@/Layouts/AdminLayout';
import { PageHeader, SequenceCodeField, type CodeSequence } from '@/Components/composite';
import {
    Button,
    Card,
    CardContent,
    CardHeader,
    CardTitle,
    Input,
    SearchSelect,
    Switch,
    Textarea,
} from '@/Components/ui';
import type { Category } from '@/types/inventory';

interface CreateProps extends Record<string, unknown> {
    categories: { data: Category[] };
    codeSequence: CodeSequence;
}

export default function Create({ categories, codeSequence }: CreateProps) {
    const { data, setData, post, transform, processing, errors } = useForm({
        sku: '',
        name: '',
        category_id: '',
        description: '',
        sell_price: '',
        cost_price: '',
        min_stock: '',
        track_stock: true,
        is_active: true,
    });

    const categoryChoices = categories.data.map((c) => ({
        value: String(c.id),
        label: `${c.code} - ${c.name}`,
        description: c.unit ? `Satuan: ${c.unit.name} (${c.unit.symbol})` : undefined,
    }));
    const selectedCategory = categories.data.find(
        (category) => String(category.id) === String(data.category_id),
    );
    const unitLabel = selectedCategory?.unit
        ? `${selectedCategory.unit.name} (${selectedCategory.unit.symbol})`
        : 'Pilih kategori dulu';

    const submit = (e: FormEvent) => {
        e.preventDefault();
        // A locked SKU is generated by the server; sending it would be rejected.
        if (!codeSequence.manual) transform(({ sku: _sku, ...values }) => values);
        post(route('admin.products.store'));
    };

    return (
        <AdminLayout title="Buat Barang">
            <div className="space-y-6">
                <PageHeader
                    title="Buat Barang"
                    subtitle="Isi data barang, lalu simpan."
                    actions={
                        <Button
                            asChild
                            variant="outline"
                            size="sm"
                            leftIcon={<ArrowLeft className="size-4" />}
                        >
                            <Link href={route('admin.products.index')}>Kembali</Link>
                        </Button>
                    }
                />

                <form onSubmit={submit} className="space-y-6">
                    <Card>
                        <CardHeader>
                            <CardTitle>Data Barang</CardTitle>
                        </CardHeader>
                        <CardContent className="grid gap-4 md:grid-cols-2">
                            <SequenceCodeField
                                label="SKU"
                                value={data.sku}
                                onChange={(next) => setData('sku', next)}
                                error={errors.sku}
                                sequence={codeSequence}
                                mode="create"
                            />
                            <Input
                                label="Nama"
                                value={data.name}
                                onChange={(e) => setData('name', e.target.value)}
                                error={errors.name}
                                required
                            />
                            <SearchSelect
                                id="product-category"
                                label="Kategori"
                                placeholder="Cari kategori"
                                emptyText="Tidak ada kategori yang cocok."
                                options={categoryChoices}
                                value={data.category_id}
                                onChange={(value) => setData('category_id', value)}
                                error={errors.category_id}
                                required
                            />
                            <Input
                                label="Satuan"
                                value={unitLabel}
                                readOnly
                                disabled
                                hint="Satuan mengikuti kategori yang dipilih."
                            />
                            <Input
                                label="Harga Jual"
                                type="number"
                                step="0.01"
                                value={data.sell_price}
                                onChange={(e) => setData('sell_price', e.target.value)}
                                error={errors.sell_price}
                            />
                            <Input
                                label="Harga Pokok"
                                type="number"
                                step="0.01"
                                value={data.cost_price}
                                onChange={(e) => setData('cost_price', e.target.value)}
                                error={errors.cost_price}
                            />
                            <Input
                                label="Stok Minimum"
                                type="number"
                                step="0.01"
                                value={data.min_stock}
                                onChange={(e) => setData('min_stock', e.target.value)}
                                error={errors.min_stock}
                            />
                            <div className="flex items-center gap-6">
                                <Switch
                                    label="Lacak stok"
                                    checked={data.track_stock}
                                    onCheckedChange={(checked) => setData('track_stock', checked)}
                                />
                                <Switch
                                    label="Aktif"
                                    checked={data.is_active}
                                    onCheckedChange={(checked) => setData('is_active', checked)}
                                />
                            </div>
                            <div className="md:col-span-2">
                                <Textarea
                                    label="Deskripsi"
                                    value={data.description}
                                    onChange={(e) => setData('description', e.target.value)}
                                    error={errors.description}
                                    rows={3}
                                />
                            </div>
                        </CardContent>
                    </Card>
                    <div className="flex justify-end gap-2">
                        <Button
                            type="button"
                            variant="outline"
                            onClick={() => router.get(route('admin.products.index'))}
                        >
                            Batal
                        </Button>
                        <Button type="submit" variant="primary" loading={processing}>
                            Simpan
                        </Button>
                    </div>
                </form>
            </div>
        </AdminLayout>
    );
}
